"""Post-registration correction of a sample's receipt and collection dates (Céluma 1.4).

The monthly code of a sample is numbered by its RECEIPT date (`monthly-numbering.md`), and a receipt date
never changes a code by itself. So this edit is deliberately narrow:

- Lifecycle: same window and evidence guard as every direct edit (`order_lifecycle.lock_and_guard`).
- `received_at` may move freely inside its numbering period (year and month in the numbering zone). When it
  moves into ANOTHER month and the sample's current code was generated by monthly numbering for this sample
  (`code_follows_receipt_month`), the code is REGENERATED in the new month: a fresh code is allocated from
  that month's counter (ledger row, same scope/branch rules as registration), the old code is retired exactly
  like a correction (`sample_code_correction` row with the reason, never reusable), and the old month's counter
  is never lowered (it keeps a gap). A typed/corrected or legacy code does not encode a month and is kept.
  A sample with no stored receipt date has no period to protect.
- `collected_at` is independent of numbering and may also be cleared.
- Audit: a timeline event, an `audit_log` row and the reason, in the same transaction (plus a
  `SAMPLE_CODE_CORRECTED` event and `SAMPLE.CODE_REGENERATED` audit row when the code is regenerated).
  Nothing else of the sample (state, notes, images, relationships) is touched.

Locks: the order lifecycle lock first (as sample registration does), then counter rows and TRY-locks on
candidate codes inside the allocator, so it cannot deadlock with registration or a code correction (which
waits on a code lock before the order lock, while the allocator never waits on a code lock).
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Optional

from fastapi import HTTPException
from sqlalchemy import text
from sqlmodel import Session, select

from app.models.enums import EventType
from app.models.events import OrderEvent
from app.models.laboratory import Sample
from app.models.order_management import SampleCodeCorrection
from app.models.sample_type import SampleType
from app.models.tenant import Branch
from app.services import numbering, order_lifecycle
from app.services.order_management import ManagementError
from app.services.sample_code_correction import clean_reason
from app.services.sample_types import record_audit


@dataclass
class DatesResult:
    sample: Sample
    unchanged: bool
    #: The code before a regeneration (None when the code did not change).
    old_code: Optional[str] = None


def code_follows_receipt_month(session: Session, sample: Sample, settings: numbering.NumberingSettings) -> bool:
    """The sample's CURRENT code was issued by active monthly numbering for this very sample, so it encodes
    (and is counted in) its receipt month. Typed, corrected and legacy codes do not."""
    if not settings.active or sample.sample_type_id is None or sample.received_at is None:
        return False
    return bool(session.execute(text(
        "SELECT EXISTS (SELECT 1 FROM numbering_allocation WHERE tenant_id = :t AND entity_kind = :k "
        "AND entity_id = :e AND code = :c AND scheme = :scheme)"),
        {"t": str(sample.tenant_id), "k": numbering.SAMPLE, "e": str(sample.id), "c": sample.sample_code,
         "scheme": numbering.SCHEME_MONTHLY},
    ).scalar())


def _iso(value: Optional[datetime]) -> Optional[str]:
    return value.isoformat() if value else None


def update_sample_dates(
    session: Session, *, sample_id, tenant_id, user, fields: set, received_at: Optional[datetime],
    collected_at: Optional[datetime], reason: str,
) -> DatesResult:
    reason = clean_reason(reason)
    sample = session.get(Sample, sample_id)
    if sample is None or str(sample.tenant_id) != str(tenant_id):
        raise HTTPException(404, "Sample not found")

    order = order_lifecycle.lock_and_guard(session, sample.order_id, tenant_id)
    sample = session.exec(
        select(Sample).where(Sample.id == sample_id, Sample.tenant_id == tenant_id)
        .execution_options(populate_existing=True)
    ).first()
    if sample is None:  # removed while we waited for the lock
        raise HTTPException(404, "Sample not found")

    branch = session.get(Branch, sample.branch_id)
    settings = numbering.get_settings(session, tenant_id, numbering.SAMPLE)
    zone = settings.zone_name(getattr(branch, "timezone", None))
    regenerate = False

    old = {"received_at": _iso(sample.received_at), "collected_at": _iso(sample.collected_at)}
    new_received, new_collected = sample.received_at, sample.collected_at

    if "received_at" in fields:
        if received_at is None:
            raise ManagementError(422, "sample_receipt_required", "The receipt date cannot be cleared")
        new_received = numbering.receipt_local(received_at, zone)
        if sample.received_at is not None:
            before = numbering.receipt_period(sample.received_at, zone)
            after = numbering.receipt_period(new_received, zone)
            regenerate = (before.year, before.month) != (after.year, after.month) and code_follows_receipt_month(
                session, sample, settings)
    if "collected_at" in fields:
        new_collected = numbering.receipt_local(collected_at, zone) if collected_at is not None else None

    if new_received == sample.received_at and new_collected == sample.collected_at:
        session.rollback()  # nothing to write: release the locks
        return DatesResult(sample, True)

    old_code = None
    if regenerate:
        old_code = _regenerate_code(session, sample=sample, branch=branch, settings=settings,
                                    received_local=new_received, user=user, reason=reason, order=order)
    sample.received_at, sample.collected_at = new_received, new_collected
    session.add(sample)
    new = {"received_at": _iso(new_received), "collected_at": _iso(new_collected)}
    changed = sorted(k for k in new if new[k] != old[k])
    session.add(OrderEvent(
        tenant_id=sample.tenant_id, branch_id=sample.branch_id, order_id=sample.order_id, sample_id=sample.id,
        event_type=EventType.ORDER_UPDATED, description="",
        event_metadata={
            "order_id": str(order.id), "order_code": order.order_code, "sample_id": str(sample.id),
            "sample_code": sample.sample_code, "old_code": old_code, "changed_fields": changed,
            "old": {k: old[k] for k in changed}, "new": {k: new[k] for k in changed}, "reason": reason,
        },
        created_by=user.id,
    ))
    record_audit(
        session, tenant_id=sample.tenant_id, user_id=user.id, action="SAMPLE.DATES_UPDATED",
        entity_type="sample", entity_id=sample.id, description="Sample dates updated",
        old_values={k: old[k] for k in changed}, new_values={k: new[k] for k in changed},
        metadata={"reason": reason, "order_id": str(sample.order_id)},
    )
    session.commit()
    session.refresh(sample)
    return DatesResult(sample, False, old_code)


def _regenerate_code(session: Session, *, sample: Sample, branch, settings, received_local: datetime, user, reason: str,
                     order) -> str:
    """Allocate the sample's code in its new receipt month and retire the old one (caller holds the order lock)."""
    sample_type = session.get(SampleType, sample.sample_type_id)
    if sample_type is None:
        raise ManagementError(409, "sample_code_not_regenerable",
                              "This sample has no type to number it with; correct its code instead")
    allocation = numbering.allocate_batch(
        session, tenant_id=sample.tenant_id, instant=numbering.now(),
        requests=[numbering.AllocationRequest(
            "sample", numbering.SAMPLE, sample_type.id, sample_type.code, branch.id, branch.code, branch.timezone,
            received_at=received_local)],
        settings_by_kind={numbering.SAMPLE: settings}, actor_id=user.id,
    )["sample"]
    numbering.attach_entity(session, allocation, sample.id)
    old_code = sample.sample_code
    sample.sample_code = allocation.code
    session.add(SampleCodeCorrection(
        tenant_id=sample.tenant_id, sample_id=sample.id, order_id=sample.order_id,
        old_code=old_code, new_code=allocation.code, reason=reason, corrected_by=user.id, corrected_at=datetime.utcnow(),
    ))
    session.add(OrderEvent(
        tenant_id=sample.tenant_id, branch_id=sample.branch_id, order_id=sample.order_id, sample_id=sample.id,
        event_type=EventType.SAMPLE_CODE_CORRECTED, description="",
        event_metadata={
            "sample_id": str(sample.id), "old_code": old_code, "new_code": allocation.code, "reason": reason,
            "order_code": order.order_code, "regenerated": True, "trigger": "received_at",
        },
        created_by=user.id,
    ))
    record_audit(
        session, tenant_id=sample.tenant_id, user_id=user.id, action="SAMPLE.CODE_REGENERATED",
        entity_type="sample", entity_id=sample.id, description="Sample code regenerated for a new receipt month",
        old_values={"sample_code": old_code}, new_values={"sample_code": allocation.code},
        metadata={"reason": reason, "order_id": str(sample.order_id),
                  "period": f"{allocation.period.year:04d}-{allocation.period.month:02d}"},
    )
    return old_code
